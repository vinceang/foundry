#!/usr/bin/env node
// One-off: turn Natural Earth 110m land polygons into a single SVG path for
// Auriga's Board chart, clipped to the chart window and projected with the
// same Mercator transform the cities and routes use.
//
//   node tools/gen-chart-land.mjs <ne_110m_land.geojson> > sites/auriga/src/data/land.js

import { readFileSync } from "node:fs";
import { project, VIEW } from "../sites/auriga/src/lib/geo.js";

const PAD = 40; // keep a little geometry beyond the frame so coasts run off-edge
const src = JSON.parse(readFileSync(process.argv[2], "utf8"));

const rings = [];
for (const f of src.features) {
  const polys =
    f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      const pts = ring.map(([lon, lat]) => project(lat, lon));
      // drop rings entirely outside the frame
      const inside = pts.some(
        ([x, y]) => x > -PAD && x < VIEW.w + PAD && y > -PAD && y < VIEW.h + PAD
      );
      if (!inside) continue;
      // clamp rather than true-clip: cheap, and the frame hides the edges
      const clamped = pts.map(([x, y]) => [
        Math.max(-PAD, Math.min(VIEW.w + PAD, x)),
        Math.max(-PAD, Math.min(VIEW.h + PAD, y)),
      ]);
      if (ringArea(clamped) < 6) continue; // drop specks
      const thinned = simplify(clamped, 1.2); // sub-pixel detail is wasted at 800px
      if (thinned.length > 3) rings.push(thinned);
    }
  }
}

/** Douglas-Peucker. */
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const sqTol = tol * tol;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [lo, hi] = stack.pop();
    let far = -1, best = sqTol;
    const [ax, ay] = pts[lo], [bx, by] = pts[hi];
    const dx = bx - ax, dy = by - ay;
    const len = dx * dx + dy * dy;
    for (let i = lo + 1; i < hi; i++) {
      const [px, py] = pts[i];
      let t = len ? ((px - ax) * dx + (py - ay) * dy) / len : 0;
      t = t < 0 ? 0 : t > 1 ? 1 : t;
      const ex = px - (ax + t * dx), ey = py - (ay + t * dy);
      const sq = ex * ex + ey * ey;
      if (sq > best) { best = sq; far = i; }
    }
    if (far > 0) { keep[far] = 1; stack.push([lo, far], [far, hi]); }
  }
  return pts.filter((_, i) => keep[i]);
}

function ringArea(p) {
  let a = 0;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++)
    a += (p[j][0] + p[i][0]) * (p[j][1] - p[i][1]);
  return Math.abs(a / 2);
}

const d = rings
  .map((r) => r.map(([x, y], i) => `${i ? "L" : "M"}${x.toFixed(1)} ${y.toFixed(1)}`).join("") + "Z")
  .join("");

process.stdout.write(
  `// Generated by tools/gen-chart-land.mjs from Natural Earth 110m land.\n` +
    `// Projected with src/lib/geo.js — regenerate if the projection changes.\n` +
    `export const LAND = ${JSON.stringify(d)};\n`
);
process.stderr.write(`${rings.length} rings, ${d.length} chars\n`);
